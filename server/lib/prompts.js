function stopSystem(profile) {
  const simple = profile.level === 'beginner' && profile.storyLang === 'ru'
    ? '\nПосетитель только начинает учить русский, а язык ответа русский: фразы короткие и простые, не длиннее 10 слов.'
    : '';
  return `Ты пишешь материалы одной остановки квеста «Зачёт у профессора Цветаева» в Пушкинском музее для иностранного студента.
Язык всех текстов — язык рассказа из данных (storyLanguage), кроме полей word.ru и word.transcription. Обращение на «ты».
Без искусствоведческих терминов. Рассказ начинается с того, что видно глазами.${simple}
Используй только факты из данных экспоната и общеизвестные сведения. Правильный ответ задания обязательно подтверждается данными экспоната.

Задание «найди деталь» связано с культурой страны посетителя. Перед вопросом напиши одну фразу-подводку (task.lead):
число, символ, обычай, пословица или знакомый образ из его культуры — чтобы поиск детали стал личным открытием «это есть и у меня дома».
Правила подводки: это настоящий проверяемый факт о культуре, без стереотипов и без шуток о религии; формулировка «в культуре Китая…»,
а не «ты считаешь…» — страна не равна убеждениям человека; задание может просить найти несколько предметов, если все они названы
в данных экспоната; правильный ответ подтверждается данными экспоната, а не культурным фактом; если страна не указана или честной
связи нет — подводка строится на специальности или студенческой жизни.
${LEAD_EXAMPLES}
${DATA_RULE}

Ответ — строго JSON такого вида:
{"caption":"подпись для открытки, до 60 знаков","story":"рассказ, 3–4 коротких предложения","forYou":"факт, связанный со специальностью или страной",
"task":{"lead":"подводка","question":"вопрос","options":["...","...","..."],"correct":0,"hint":"подсказка","explain":"пояснение после верного ответа"},
"voiceTopic":"тема для 20-секундного голосового семье","word":{"ru":"русское слово","transcription":"[транскрипция латиницей]","translation":"перевод"}}
В options ровно три варианта, correct — номер верного от 0 до 2.`;
}

export function planMessages(profile, catalog, n) {
  return [
    { role: 'system', text: PLAN_SYSTEM },
    {
      role: 'user',
      text: JSON.stringify({ N: n, visitor: describeProfile(profile), catalog: catalog.map(catalogLine) }),
    },
  ];
}

export function stopMessages(profile, exhibit, reason) {
  return [
    { role: 'system', text: stopSystem(profile) },
    {
      role: 'user',
      text: JSON.stringify({
        visitor: describeProfile(profile),
        reason,
        exhibit: {
          name: exhibit.name,
          author: exhibit.author,
          date: exhibit.period,
          country: exhibit.country,
          type: exhibit.type,
          material: exhibit.material,
          size: exhibit.size,
          cast: exhibit.cast,
          description: description(exhibit).slice(0, 3500),
        },
      }),
    },
  ];
}
